# ==============================================================================
# CounterYield Android & Full-Stack Auto-Launcher
# ==============================================================================
# Purpose:
#   1. Resolves local LAN IPv4 address (e.g. 192.168.8.11) so physical Android devices
#      running Expo Go can access the backend server.
#   2. Validates and auto-generates mobile/.env with correct LAN endpoints.
#   3. Searches for Android SDK / ADB / Emulators and configures reverse port forwarding.
#   4. Checks and launches the Backend Fastify API (port 4000).
#   5. Launches the Expo Metro bundler for Android with QR code and auto-open.
# ==============================================================================

param (
    [switch]$SkipBackend = $false,
    [switch]$NoBrowser = $false
)

$ErrorActionPreference = "Stop"

Write-Host ""
Write-Host "==========================================================" -ForegroundColor Green
Write-Host "  CounterYield - Android Full-Stack Auto-Launcher        " -ForegroundColor Green
Write-Host "  Delta-Neutral Carry Protocol on Monad Testnet          " -ForegroundColor DarkGreen
Write-Host "==========================================================" -ForegroundColor Green
Write-Host ""

$WorkspaceRoot = (Resolve-Path "$PSScriptRoot\..").Path
Set-Location $WorkspaceRoot

# ------------------------------------------------------------------------------
# 1. Resolve LAN IPv4 Address
# ------------------------------------------------------------------------------
Write-Host "[1/5] Detecting LAN IPv4 address for Android device connectivity..." -ForegroundColor Cyan

$LanIp = "192.168.8.11"
try {
    $ipOutput = & node "$WorkspaceRoot\scripts\get_lan_ip.js"
    if ($ipOutput -and $ipOutput.Trim()) {
        $LanIp = $ipOutput.Trim()
        Write-Host "  -> Active Host LAN IP: $LanIp" -ForegroundColor Green
    }
} catch {
    Write-Host "  -> Using default LAN IP: $LanIp" -ForegroundColor Yellow
}

# ------------------------------------------------------------------------------
# 2. Configure mobile/.env
# ------------------------------------------------------------------------------
Write-Host "[2/5] Checking mobile/.env configuration..." -ForegroundColor Cyan
$MobileEnvPath = Join-Path $WorkspaceRoot "mobile\.env"
$DeployedLedger = "0x9998a7776edddf2f2ab6ffbb9420e5194a50f906"

$EnvContent = @"
# Auto-generated by launch_android.ps1
EXPO_PUBLIC_API_URL=http://${LanIp}:4000
EXPO_PUBLIC_ENVIO_URL=http://${LanIp}:8080/v1/graphql
EXPO_PUBLIC_RP_ID=counteryield.app
EXPO_PUBLIC_LEDGER_ADDRESS=$DeployedLedger
EXPO_PUBLIC_MONAD_RPC_URL=https://testnet-rpc.monad.xyz
EXPO_PUBLIC_EXPLORER_URL=https://testnet.monadscan.com
"@

Set-Content -Path $MobileEnvPath -Value $EnvContent -Encoding UTF8
Write-Host "  -> Updated mobile/.env with API: http://${LanIp}:4000" -ForegroundColor Green

# ------------------------------------------------------------------------------
# 3. Detect Android SDK / ADB / Connected Devices
# ------------------------------------------------------------------------------
Write-Host "[3/5] Inspecting Android environment..." -ForegroundColor Cyan

$AdbCmd = Get-Command adb -ErrorAction SilentlyContinue

if (-not $AdbCmd) {
    # Check common Android SDK directories
    $PossibleSdkDirs = @(
        "$env:LOCALAPPDATA\Android\Sdk\platform-tools",
        "E:\Android Studio\bin",
        "E:\sdk\platform-tools",
        "C:\Program Files\Android\Android Studio\bin"
    )
    foreach ($dir in $PossibleSdkDirs) {
        if (Test-Path "$dir\adb.exe") {
            $env:PATH = "$dir;" + $env:PATH
            $AdbCmd = Get-Command adb -ErrorAction SilentlyContinue
            break
        }
    }
}

$AdbDeviceFound = $false
if ($AdbCmd) {
    Write-Host "  -> ADB located at: $($AdbCmd.Source)" -ForegroundColor Green
    try {
        $devices = & adb devices | Select-Object -Skip 1 | Where-Object { $_ -match "\bdevice\b" }
        if ($devices) {
            Write-Host "  -> Connected Android Device / Emulator detected!" -ForegroundColor Green
            $AdbDeviceFound = $true
            Write-Host "  -> Setting up ADB reverse port forwarding (4000, 8081)..." -ForegroundColor DarkGray
            & adb reverse tcp:4000 tcp:4000 2>$null
            & adb reverse tcp:8081 tcp:8081 2>$null
        } else {
            Write-Host "  -> No USB or running emulator attached. Expo Go via LAN QR code will be used." -ForegroundColor Yellow
        }
    } catch {
        Write-Host "  -> ADB check skipped." -ForegroundColor Yellow
    }
} else {
    Write-Host "  -> No local ADB found. Using Expo Go QR mode (Zero-setup physical Android phone)." -ForegroundColor Yellow
    Write-Host "     (To test: open Expo Go app on your Android phone and scan the QR code)." -ForegroundColor DarkGray
}

# ------------------------------------------------------------------------------
# 4. Start Backend Server
# ------------------------------------------------------------------------------
if (-not $SkipBackend) {
    Write-Host "[4/5] Checking Backend Fastify Server..." -ForegroundColor Cyan
    
    $BackendRunning = $false
    try {
        $resp = Invoke-WebRequest -Uri "http://localhost:4000/api/v1/health" -Method Get -TimeoutSec 2 -ErrorAction SilentlyContinue
        if ($resp -and $resp.StatusCode -eq 200) {
            $BackendRunning = $true
            Write-Host "  -> Backend is ALREADY RUNNING on http://localhost:4000 (Health OK)" -ForegroundColor Green
        }
    } catch {
        $BackendRunning = $false
    }

    if (-not $BackendRunning) {
        Write-Host "  -> Launching Backend in a separate window..." -ForegroundColor Cyan
        Start-Process powershell -ArgumentList "-NoExit", "-Command", "cd '$WorkspaceRoot'; Write-Host 'CounterYield Backend Engine' -ForegroundColor Green; npm --workspace=backend run dev" -WindowStyle Normal

        Write-Host "  -> Waiting for Backend to be healthy..." -NoNewline
        $attempts = 0
        while ($attempts -lt 15) {
            Start-Sleep -Seconds 1
            $attempts++
            try {
                $resp = Invoke-WebRequest -Uri "http://localhost:4000/api/v1/health" -Method Get -TimeoutSec 1 -ErrorAction SilentlyContinue
                if ($resp -and $resp.StatusCode -eq 200) {
                    $BackendRunning = $true
                    break
                }
            } catch {}
            Write-Host "." -NoNewline
        }
        Write-Host ""
        if ($BackendRunning) {
            Write-Host "  -> Backend successfully started and healthy!" -ForegroundColor Green
        } else {
            Write-Host "  -> Backend started (process spinning up)." -ForegroundColor Yellow
        }
    }
} else {
    Write-Host "[4/5] Skipping backend launch as requested." -ForegroundColor DarkGray
}

# ------------------------------------------------------------------------------
# 5. Launch Expo Metro Bundler for Android
# ------------------------------------------------------------------------------
Write-Host "[5/5] Launching Expo Metro Bundler for Android..." -ForegroundColor Cyan
Write-Host ""
Write-Host "==========================================================" -ForegroundColor Green
Write-Host "  HOW TO TEST ON ANDROID:                                 " -ForegroundColor White
Write-Host "  1. Physical Phone: Open 'Expo Go' app on Android        " -ForegroundColor Yellow
Write-Host "     and scan the QR code that appears below.             " -ForegroundColor Yellow
Write-Host "  2. Browser Preview: Press 'w' in the Metro terminal     " -ForegroundColor Yellow
if ($AdbDeviceFound) {
    Write-Host "  3. Emulator: Press 'a' to open on attached device       " -ForegroundColor Yellow
}
Write-Host "==========================================================" -ForegroundColor Green
Write-Host ""

Set-Location (Join-Path $WorkspaceRoot "mobile")

# Launch expo start in current terminal
if ($AdbDeviceFound) {
    npx expo start --android
} else {
    npx expo start
}
